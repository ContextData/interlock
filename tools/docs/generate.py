def codebase_map_page() -> str:
    import ast

    package_root = ROOT / "src" / "interlock"
    rows = []
    for init in sorted(package_root.glob("*/__init__.py")):
        tree = ast.parse(init.read_text(encoding="utf-8"))
        doc = (ast.get_docstring(tree) or "").strip().splitlines()
        rows.append([_code(f"interlock.{init.parent.name}"), doc[0] if doc else ""])
    parts = [
        _md_frontmatter(
            "Codebase map",
            "The Python packages under src/interlock and what each one is for.",
            "each package's docstring",
            extra="sidebar:\n  order: 3\n",
        ),
        "The runtime is one Python package, `interlock`, with the services as "
        "entry points (`python -m interlock.gateway`, `.admin`, `.worker`). "
        "Database migrations are in `migrations/`, the Helm chart and deployment "
        "scripts in `deploy/`, tests in `tests/`, and this site in `docs-site/`.\n\n",
        _table(["Package", "What it holds"], rows),
    ]
    return "".join(parts)


# --- driver --------------------------------------------------------------------


def outputs() -> dict[Path, Callable[[], str]]:
    reference = DOCS / "reference"
    files: dict[Path, Callable[[], str]] = {
        reference / "configuration.md": configuration_page,
        reference / "admin-api.md": admin_api_page,
        SITE / "public" / "admin-api" / "openapi.json": admin_openapi,
        reference / "admin-roles.md": admin_roles_page,
        reference / "mcp-tools.md": mcp_tools_page,
        reference / "connectors" / "index.md": connectors_index_page,
        reference / "role-conditions.md": role_conditions_page,
        reference / "feature-status.md": feature_status_page,
        reference / "make-targets.md": make_targets_page,
        DOCS / "project" / "codebase-map.md": codebase_map_page,
    }
    for d in _connector_rows():
        files[reference / "connectors" / f"{d.key}.md"] = lambda d=d: connector_page(d)
    return files


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    stale: list[str] = []
    expected = outputs()
    for path, render in sorted(expected.items()):
        content = render()
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    # A connector removed from the registry must not leave its page behind.
    connectors_dir = DOCS / "reference" / "connectors"
    if connectors_dir.exists():
        for page in sorted(connectors_dir.glob("*.md")):
            if page not in expected:
                if args.check:
                    stale.append(f"{page.relative_to(ROOT)} (no longer generated)")
                else:
                    page.unlink()
                    print(f"removed {page.relative_to(ROOT)}")
    if stale:
        print("Generated documentation is stale; run `make docs-generate`:", file=sys.stderr)
        for item in stale:
            print(f"  {item}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
