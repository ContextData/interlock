"""Generate the reference pages of the documentation site from the code.

Each page here is derived from the object it documents - the configuration
model, the admin routes and their role rules, the MCP tool list, the connector
registry, the role-condition vocabulary, the feature-status registry and the
Makefile - so the reference cannot drift from the code without this tool
noticing.

    uv run python tools/docs/generate.py --write   # regenerate
    uv run python tools/docs/generate.py --check   # fail if anything is stale

Output is deterministic. The configuration is built from defaults only: every
`INTERLOCK_*` and `ONYX_*` variable is removed from the environment first, and
no YAML file is read, so a developer's local settings never reach the docs.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections.abc import Callable, Iterable
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SITE = ROOT / "docs-site"
DOCS = SITE / "src" / "content" / "docs"

for _name in list(os.environ):
    if _name.startswith(("INTERLOCK_", "ONYX_")):
        del os.environ[_name]
if str(ROOT / "src") not in sys.path:
    sys.path.insert(0, str(ROOT / "src"))

from pydantic import BaseModel  # noqa: E402

GENERATOR = "tools/docs/generate.py"


def _md_frontmatter(title: str, description: str, source: str, extra: str = "") -> str:
    """Markdown pages carry the banner as an HTML comment, which MDX would reject."""
    return (
        "---\n"
        f"title: {json.dumps(title)}\n"
        f"description: {json.dumps(description)}\n"
        "generated: true\n"
        f"{extra}"
        "---\n\n"
        f"<!-- Generated by {GENERATOR} from {source}. Do not edit by hand. -->\n\n"
    )


def _cell(value: object) -> str:
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return text if text else " "


def _table(headers: Iterable[str], rows: Iterable[Iterable[object]]) -> str:
    headers = list(headers)
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(_cell(v) for v in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def _code(value: object) -> str:
    return f"`{value}`" if value not in ("", None) else " "


# --- configuration ------------------------------------------------------------


def _default_repr(value: object) -> str:
    if value is None:
        return "unset"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (list, dict)):
        return json.dumps(value)
    if value == "":
        return '""'
    return str(value)


def _type_name(annotation: object) -> str:
    text = getattr(annotation, "__name__", None) or str(annotation)
    text = text.replace("typing.", "")
    return re.sub(r"<class '([^']+)'>", r"\1", text)


def configuration_page() -> str:
    from interlock.config import InterLockConfig

    config = InterLockConfig()
    parts = [
        _md_frontmatter(
            "Configuration",
            "Every InterLock setting, its environment variable, default and meaning.",
            "src/interlock/config.py",
        ),
        "Settings are read, in increasing precedence, from the defaults below, a "
        "YAML file (`config.yaml`, or the path in `INTERLOCK_CONFIG_PATH`), and "
        "environment variables. A nested key `section.key` is the environment "
        "variable `INTERLOCK_SECTION__KEY`. Unknown keys are rejected at start.\n\n",
    ]
    top_level: list[list[object]] = []
    sections: list[tuple[str, type[BaseModel], BaseModel]] = []
    for name, field in InterLockConfig.model_fields.items():
        annotation = field.annotation
        if isinstance(annotation, type) and issubclass(annotation, BaseModel):
            sections.append((name, annotation, getattr(config, name)))
        else:
            top_level.append(
                [
                    _code(name),
                    _code(f"INTERLOCK_{name.upper()}"),
                    _code(_default_repr(getattr(config, name))),
                    field.description or "",
                ]
            )
    parts.append("## Top level\n\n")
    parts.append(_table(["Key", "Environment variable", "Default", "Meaning"], top_level))
    for section, model, value in sections:
        parts.append(f"\n## `{section}`\n\n")
        section_field = InterLockConfig.model_fields[section]
        if section_field.description:
            parts.append(section_field.description + "\n\n")
        rows: list[list[object]] = []
        for name, field in model.model_fields.items():
            annotation = field.annotation
            if isinstance(annotation, type) and issubclass(annotation, BaseModel):
                nested = getattr(value, name)
                for sub, subfield in annotation.model_fields.items():
                    rows.append(
                        [
                            _code(f"{section}.{name}.{sub}"),
                            _code(f"INTERLOCK_{section.upper()}__{name.upper()}__{sub.upper()}"),
                            _code(_default_repr(getattr(nested, sub))),
                            subfield.description or "",
                        ]
                    )
                continue
            rows.append(
                [
                    _code(f"{section}.{name}"),
                    _code(f"INTERLOCK_{section.upper()}__{name.upper()}"),
                    _code(_default_repr(getattr(value, name))),
                    field.description or "",
                ]
            )
        parts.append(_table(["Key", "Environment variable", "Default", "Meaning"], rows))
    return "".join(parts)


# --- admin API and roles -----------------------------------------------------

ROLE_MEANINGS = {
    "owner": "Everything, including admin accounts. The first admin is an owner.",
    "admin": "Everything, like owner.",
    "security_admin": "Identities, keys and grants; any mutation without a narrower rule.",
    "source_admin": "Data sources, connectors, source roles, catalog and ingestion.",
    "policy_admin": "Policy rules.",
    "approval_reviewer": "Reviewing queued writes: approve and reject.",
    "auditor": "Read-only access to the console, audit and usage.",
}


def _admin_app() -> Any:
    from interlock.admin.app import create_app
    from interlock.config import InterLockConfig

    config = InterLockConfig()
    config.admin.secret_key = "documentation-generator-only-key-not-used"
    return create_app(config=config)


def _admin_routes() -> list[tuple[str, str, str, str]]:
    """(path, method, summary, tag) for every documented admin route."""
    app = _admin_app()
    rows = []
    for route in app.routes:
        path = getattr(route, "path", "")
        methods = sorted((getattr(route, "methods", None) or set()) - {"HEAD", "OPTIONS"})
        if not path or not methods or path.startswith("/static"):
            continue
        if not getattr(route, "include_in_schema", True):
            continue
        endpoint = getattr(route, "endpoint", None)
        doc = (getattr(endpoint, "__doc__", None) or "").strip().splitlines()
        summary = doc[0].strip() if doc else ""
        tag = path.strip("/").split("/")[0] or "root"
        for method in methods:
            rows.append((path, method, summary, tag))
    return sorted(set(rows))


def _roles_cell(path: str, method: str) -> str:
    from interlock.admin.auth_middleware import required_roles

    public = ("/health", "/ready", "/auth/login", "/auth/oidc", "/auth/csrf")
    if path in public or any(path.startswith(p + "/") for p in public):
        return "public"
    roles = required_roles(path, method)
    if roles is None:
        return "any signed-in admin"
    return ", ".join(["owner", "admin", *sorted(roles)])


def admin_api_page() -> str:
    rows = _admin_routes()
    parts = [
        _md_frontmatter(
            "Admin API",
            "Every admin route, the roles that may call it, and the OpenAPI document.",
            "the admin application's routes and auth_middleware.required_roles()",
        ),
        "The console and its JSON API share one server. Every route except the "
        "public ones needs a signed-in admin session; `POST`, `PUT`, `PATCH` and "
        "`DELETE` also need the `X-CSRF-Token` header from `GET /auth/csrf`. The "
        "machine-readable description is [openapi.json](/admin-api/openapi.json).\n\n",
    ]
    tags: dict[str, list[tuple[str, str, str, str]]] = {}
    for row in rows:
        tags.setdefault(row[3], []).append(row)
    for tag in sorted(tags):
        parts.append(f"## `/{tag}`\n\n")
        parts.append(
            _table(
                ["Method", "Path", "Roles", "Summary"],
                [
                    [method, _code(path), _roles_cell(path, method), summary]
                    for path, method, summary, _ in tags[tag]
                ],
            )
        )
        parts.append("\n")
    return "".join(parts).rstrip("\n") + "\n"


def admin_openapi() -> str:
    spec = _admin_app().openapi()
    return json.dumps(spec, indent=2, sort_keys=True) + "\n"


