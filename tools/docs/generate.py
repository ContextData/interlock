# --- make targets ------------------------------------------------------------


def make_targets_page() -> str:
    makefile = (ROOT / "Makefile").read_text()
    rows = []
    for line in makefile.splitlines():
        match = re.match(r'\s*@echo "  ([a-z0-9-]+)\s+(.*)"\s*$', line)
        if match:
            rows.append([_code(f"make {match.group(1)}"), match.group(2).strip()])
    parts = [
        _md_frontmatter(
            "Make targets",
            "The development, test and release targets in the Makefile.",
            "the Makefile's help text",
        ),
        "Run `make help` for the same list.\n\n",
        _table(["Target", "What it does"], rows),
    ]
    return "".join(parts)


