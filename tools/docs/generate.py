def connectors_index_page() -> str:
    from interlock.connections.activation import DEFAULT_ACTIVE_CONNECTOR_KEYS
    from interlock.feature_status import GOVERNANCE_UNVERIFIED_CONNECTORS

    parts = [
        _md_frontmatter(
            "Connectors",
            "Every connector in the registry: its status, and whether it starts active.",
            "interlock.connections.connectors.CONNECTOR_DEFINITIONS",
            extra="sidebar:\n  order: 0\n",
        ),
        "A source is registered on a connector. `planned` connectors have no "
        "working adapter and can never be activated. A fresh deployment starts "
        "with the connectors marked *active by default*; a source admin can "
        "activate others from the Connectors page.\n\n",
    ]
    if (DOCS / "reference" / "connector-support-matrix.md").exists():
        parts.append(
            "What each status means, and what has been certified, is in the "
            "[connector support matrix](/reference/connector-support-matrix/).\n\n"
        )
    rows = []
    for d in _connector_rows():
        notes = []
        if d.key in GOVERNANCE_UNVERIFIED_CONNECTORS:
            notes.append("governance not exercised by any test stack")
        rows.append(
            [
                f"[{d.name}](/reference/connectors/{d.key}/)",
                _code(d.key),
                d.status,
                "yes" if d.key in DEFAULT_ACTIVE_CONNECTOR_KEYS else "no",
                "; ".join(notes),
            ]
        )
    parts.append(_table(["Connector", "Key", "Status", "Active by default", "Note"], rows))
    return "".join(parts)


def connector_page(d: Any) -> str:
    from interlock.connections.activation import DEFAULT_ACTIVE_CONNECTOR_KEYS
    from interlock.feature_status import GOVERNANCE_UNVERIFIED_CONNECTORS

    caps = {k: v for k, v in vars_of(d.capabilities).items() if v}
    parts = [
        _md_frontmatter(
            d.name,
            f"The {d.name} connector: configuration keys, capabilities and role templates.",
            f"CONNECTOR_DEFINITIONS[{d.key!r}]",
        ),
        f"{d.description}\n\n",
        _table(
            ["Property", "Value"],
            [
                ["Key", _code(d.key)],
                ["Source type", _code(d.source_type)],
                ["Status", d.status],
                ["Active by default", "yes" if d.key in DEFAULT_ACTIVE_CONNECTOR_KEYS else "no"],
                ["Default cache strategy", _code(d.default_cache_strategy)],
                ["Capabilities", ", ".join(sorted(caps)) or "none"],
            ],
        ),
    ]
    if d.key in GOVERNANCE_UNVERIFIED_CONNECTORS:
        parts.append(
            "\n:::caution\nNo test stack registers a source on this connector, so its "
            "source roles, policy, redaction and audit are not exercised by any test. "
            "The adapter works; its governance is unproven.\n:::\n"
        )
    if d.credential_fields or d.secret_fields:
        parts.append("\n## Connection configuration\n\n")
        parts.append(
            "Secret fields should be given as a reference, `<field>_ref`, such as "
            "`env://NAME`, rather than a literal.\n\n"
        )
        rows = [[_code(f), "no"] for f in d.credential_fields]
        rows += [[_code(f), f"yes; prefer {_code(f + '_ref')}"] for f in d.secret_fields]
        parts.append(_table(["Key", "Secret"], rows))
    if d.role_templates:
        parts.append("\n## Default role templates\n\n")
        parts.append("Offered when a source is created with default roles. Edit them to fit.\n\n")
        for role in sorted(d.role_templates):
            parts.append(f"### `{role}`\n\n")
            parts.append(
                _table(
                    ["Effect", "Action", "Resource type", "Pattern"],
                    [
                        [
                            s.get("effect", ""),
                            _code(s.get("action", "")),
                            _code(s.get("resource_type", "")),
                            _code(s.get("resource_pattern", "")),
                        ]
                        for s in d.role_templates[role]
                    ],
                )
            )
            parts.append("\n")
    return "".join(parts).rstrip("\n") + "\n"


def vars_of(obj: Any) -> dict[str, Any]:
    from dataclasses import asdict

    return asdict(obj)


