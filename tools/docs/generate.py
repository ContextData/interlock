def feature_status_page() -> str:
    from interlock.feature_status import FEATURE_STATUSES

    labels = {"stable": "Stable", "beta": "Beta", "disabled": "Disabled", "planned": "Planned"}

    def state(f: Any) -> str:
        return f"`{labels.get(f.state, f.state)}`"

    enabled = [f for f in FEATURE_STATUSES if f.public_beta]
    held = [f for f in FEATURE_STATUSES if not f.public_beta]
    parts = [
        _md_frontmatter(
            "Feature status",
            "What is beta, disabled or planned, with the evidence and limitation for each.",
            "src/interlock/feature_status.py",
        ),
        "This page is the public-beta honesty contract. A capability is shown as "
        "enabled in the console, the README or these docs only if it is listed "
        "under current capabilities here with matching evidence. Anything listed "
        "as `Disabled` or `Planned` stays hidden, appears disabled, or is labelled "
        "as not part of the public beta. The console reads the same registry, so "
        "the two cannot disagree.\n\n",
        "## Status legend\n\n",
        "- `Certified`: local compose or equivalent certification is repeatable.\n"
        "- `Beta`: implemented and test-covered, but needs broader certification "
        "before stronger claims.\n"
        "- `Disabled`: code or configuration may exist, but the capability is not "
        "enabled for public beta.\n"
        "- `Planned`: modeled or documented, but not wired or certified enough to "
        "expose as active functionality.\n\n",
        "## Current Public-Beta Capabilities\n\n",
        _table(
            ["Feature", "Status", "Evidence", "Public-Beta Limitation"],
            [[f.label, state(f), f.evidence, f.limitation or " "] for f in enabled],
        ),
        "\n## Disabled Or Planned Capabilities\n\n",
        _table(
            ["Feature", "Status", "Why It Is Not Public-Beta Enabled"],
            [
                [f.label, state(f), " ".join(x for x in (f.evidence, f.limitation) if x)]
                for f in held
            ],
        ),
        CODE_NOT_ON_REQUEST_PATH,
    ]
    return "".join(parts)


