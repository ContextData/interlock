def test_ports_page_matches_the_compose_file() -> None:
    compose = yaml.safe_load((ROOT / "docker-compose.yml").read_text())
    page = (CONTENT / "reference" / "ports-and-endpoints.md").read_text()
    for service, container_port in (
        ("gateway", "3000"),
        ("gateway", "5432"),
        ("admin", "9090"),
        ("postgres", "5432"),
        ("redis", "6379"),
    ):
        mappings = [str(p) for p in compose["services"][service]["ports"]]
        host = next(m.split(":")[-2] for m in mappings if m.endswith(f":{container_port}"))
        assert f"| `{container_port}` | `{host}` |" in page, (service, container_port, host)


def test_every_documentation_path_cited_in_code_exists() -> None:
    """Code comments and docstrings that cite a page must cite one that exists."""
    cited = set()
    for root in ("src", "tests", "deploy", "tools", ".github"):
        for path in (ROOT / root).rglob("*"):
            if path.suffix not in {".py", ".yaml", ".yml", ".sh", ".md"} or not path.is_file():
                continue
            for match in re.finditer(
                r"docs-site/src/content/docs/[\w/.-]+\.mdx?", path.read_text(errors="ignore")
            ):
                cited.add(match.group(0))
    assert cited, "expected code to cite documentation pages"
    missing = sorted(c for c in cited if not (ROOT / c).exists())
    assert not missing, f"cited pages that do not exist: {missing}"


def test_the_npm_lockfile_has_a_version_for_every_package() -> None:
    """A lockfile written on one platform once carried version-less stubs for
    another platform's optional packages; npm on Linux then failed `npm ci` with
    `Invalid Version`. Regenerate the lockfile on Linux if this fails."""
    lock = json.loads((SITE / "package-lock.json").read_text())
    stubs = [path for path, meta in lock["packages"].items() if path and "version" not in meta]
    assert not stubs, f"lockfile entries without a version: {stubs}"


def test_the_app_platform_spec_builds_what_the_site_defines() -> None:
    """The hosting spec must build the site the way CI does and serve its output."""
    spec = yaml.safe_load((ROOT / ".do" / "docs-app.yaml").read_text())
    [site] = spec["static_sites"]
    package = json.loads((SITE / "package.json").read_text())
    assert site["source_dir"] == "docs-site"
    assert site["github"] == {
        "repo": "ContextData/interlock",
        "branch": "main",
        "deploy_on_push": True,
    }
    assert "npm ci" in site["build_command"] and "npm run build" in site["build_command"]
    assert "build" in package["scripts"]
    assert site["output_dir"] == "dist"
    assert site["error_document"] == "404.html"
    assert package["engines"]["node"].startswith((SITE / ".nvmrc").read_text().strip())
    # Canonical URLs and the served domain must agree.
    domain = spec["domains"][0]["domain"]
    site_url = {env["key"]: env["value"] for env in site["envs"]}["DOCS_SITE_URL"]
    assert site_url == f"https://{domain}"
    assert f"'https://{domain}'" in (SITE / "astro.config.mjs").read_text()
