# SHA-256 of the maintainers' own database cluster and bucket names, so the
# check can refuse them without publishing them.
_PRIVATE_RESOURCE_DIGESTS = frozenset(
    {
        "d74201daab7b2638e67b85573bcb60241f3fe9f0de0b84324110dac7175f7ad4",
        "70e09f2bfbb9a205ff4290ef61c1bbd019bce5909ec5ac814df5d583549a52cc",
        "d9fff9ebee464a6dd163cb1b6c331727d681488a154391f486d2652a10a7bb0e",
    }
)


@pytest.mark.parametrize("path", all_pages(), ids=lambda p: str(p.relative_to(CONTENT)))
def test_pages_cite_no_private_identifiers(path) -> None:  # type: ignore[no-untyped-def]
    text = path.read_text(encoding="utf-8")
    for pattern in (
        r"/Users/",
        # The site itself is published at interlock.contextdata.dev; anything else
        # under contextdata.dev, including hosts below interlock., is private.
        r"[\w-]+\.interlock\.contextdata\.dev|(?<!interlock\.)contextdata\.dev",
        r"gmail\.com",
        r"\bAVNS_",
        r"\bdop_v1_",
        r"\bghp_[A-Za-z0-9]{10,}",
        r"\bxox[bp]-\d",
    ):
        assert not re.search(pattern, text), f"{pattern} in {path.relative_to(ROOT)}"
    for word in set(re.findall(r"[a-z0-9]+(?:-[a-z0-9]+)+", text.lower())):
        digest = hashlib.sha256(word.encode()).hexdigest()
        assert digest not in _PRIVATE_RESOURCE_DIGESTS, (
            f"a private resource name in {path.relative_to(ROOT)}"
        )


