def test_every_page_is_in_the_sidebar() -> None:
    sidebar = json.loads((SITE / "sidebar.json").read_text())
    directories = set()
    slugs = set()

    def walk(items: list[dict]) -> None:
        for item in items:
            if "autogenerate" in item:
                directories.add(item["autogenerate"]["directory"])
            if "slug" in item:
                slugs.add(item["slug"])
            if "items" in item:
                walk(item["items"])

    walk(sidebar)
    orphans = []
    for path in all_pages():
        rel = path.relative_to(CONTENT)
        if rel.parts == ("index.mdx",) or rel.parts == ("index.md",):
            continue
        slug = str(rel.with_suffix("")).removesuffix("/index")
        covered = any(slug == d or slug.startswith(d + "/") for d in directories)
        if not covered and slug not in slugs:
            orphans.append(str(rel))
    assert not orphans, f"pages missing from the sidebar: {orphans}"


def test_sidebar_groups_have_readable_labels() -> None:
    """The rc.13 evaluation saw raw folder names such as `connect-an-agent`.

    An autogenerated folder nested inside another is labelled by its directory
    name, so every group below the top level is given a label explicitly.
    """
    sidebar = json.loads((SITE / "sidebar.json").read_text())
    for group in sidebar:
        for item in group.get("items", []):
            directory = item.get("autogenerate", {}).get("directory", "")
            nested = [p for p in (CONTENT / directory).iterdir() if p.is_dir()] if directory else []
            unlabelled = [p.name for p in nested if "-" in p.name]
            assert not unlabelled, f"{directory} autogenerates groups named {unlabelled}"


